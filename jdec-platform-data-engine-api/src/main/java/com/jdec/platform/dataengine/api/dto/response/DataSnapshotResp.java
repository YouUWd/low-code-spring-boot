package com.jdec.platform.dataengine.api.dto.response;

import java.time.LocalDateTime;

public class DataSnapshotResp {
    private Long id;
    private Long moduleId;
    private Long dataId;
    private Integer versionNo;
    private String businessNo;
    private Integer finalStatusValue;
    private String jsonData;
    private String changeDiff;
    private String remark;
    private Long createdBy;
    private String createdName;
    private LocalDateTime createdDate;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getModuleId() {
        return moduleId;
    }

    public void setModuleId(Long moduleId) {
        this.moduleId = moduleId;
    }

    public Long getDataId() {
        return dataId;
    }

    public void setDataId(Long dataId) {
        this.dataId = dataId;
    }

    public Integer getVersionNo() {
        return versionNo;
    }

    public void setVersionNo(Integer versionNo) {
        this.versionNo = versionNo;
    }

    public String getBusinessNo() {
        return businessNo;
    }

    public void setBusinessNo(String businessNo) {
        this.businessNo = businessNo;
    }

    public Integer getFinalStatusValue() {
        return finalStatusValue;
    }

    public void setFinalStatusValue(Integer finalStatusValue) {
        this.finalStatusValue = finalStatusValue;
    }

    public String getJsonData() {
        return jsonData;
    }

    public void setJsonData(String jsonData) {
        this.jsonData = jsonData;
    }

    public String getChangeDiff() {
        return changeDiff;
    }

    public void setChangeDiff(String changeDiff) {
        this.changeDiff = changeDiff;
    }

    public String getRemark() {
        return remark;
    }

    public void setRemark(String remark) {
        this.remark = remark;
    }

    public Long getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(Long createdBy) {
        this.createdBy = createdBy;
    }

    public String getCreatedName() {
        return createdName;
    }

    public void setCreatedName(String createdName) {
        this.createdName = createdName;
    }

    public LocalDateTime getCreatedDate() {
        return createdDate;
    }

    public void setCreatedDate(LocalDateTime createdDate) {
        this.createdDate = createdDate;
    }
}
